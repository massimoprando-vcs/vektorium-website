@dataclass
class Node:
    tag: str | None = None
    attrs: list[tuple[str, str | None]] = field(default_factory=list)
    children: list["Node"] = field(default_factory=list)
    raw: str = ""
    kind: str = "element"
    self_closing: bool = False
    source_opening: str | None = None
    source_tag: str | None = None
    source_attrs: tuple[tuple[str, str | None], ...] | None = None
    foreign_content: bool = False

    def get(self, name: str, default: str = "") -> str:
        for key, value in self.attrs:
            if key.casefold() == name.casefold():
                return value if value is not None else ""
        return default

    def has(self, name: str) -> bool:
        return any(key.casefold() == name.casefold() for key, _ in self.attrs)

    def set(self, name: str, value: str | None) -> None:
        """Set at the original attribute position, dropping any duplicates."""
        updated: list[tuple[str, str | None]] = []
        found = False
        for key, old_value in self.attrs:
            if key.casefold() == name.casefold():
                if not found:
                    updated.append((key, value))
                    found = True
            else:
                updated.append((key, old_value))
        if not found:
            updated.append((name, value))
        self.attrs = updated

    def drop(self, name: str) -> None:
        self.attrs = [(key, value) for key, value in self.attrs if key.casefold() != name.casefold()]

    def classes(self) -> list[str]:
        return self.get("class").split()

    def add_class(self, name: str) -> None:
        current = self.classes()
        if name not in current:
            current.append(name)
            self.set("class", " ".join(current))


def text_node(value: str) -> Node:
    return Node(raw=value, kind="text")


def element(tag: str, attrs: list[tuple[str, str | None]] | None = None,
            children: list[Node] | None = None) -> Node:
    return Node(tag=tag, attrs=attrs or [], children=children or [])


class DocumentParser(HTMLParser):
    """Small loss-conscious HTML tree builder for these explicit-end-tag pages.

    Text/entities/comments are preserved.  Attribute names retain their original
    case so embedded SVG viewBox and similar attributes are not damaged.
    """

    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.document = Node(kind="document")
        self.stack = [self.document]

    def add(self, node: Node) -> None:
        self.stack[-1].children.append(node)

    def attributes(self, fallback: list[tuple[str, str | None]]) -> list[tuple[str, str | None]]:
        raw = self.get_starttag_text() or ""
        match = re.match(r"<\s*[^\s/>]+", raw)
        if not match:
            return fallback
        remainder = raw[match.end():]
        remainder = re.sub(r"/?>\s*$", "", remainder)
        result: list[tuple[str, str | None]] = []
        for item in ATTR_RE.finditer(remainder):
            name = item.group(1)
            values = item.groups()[1:]
            value = next((part for part in values if part is not None), None)
            result.append((name, html.unescape(value) if value is not None else None))
        return result

    def remember_opening(self, node: Node) -> None:
        node.source_opening = self.get_starttag_text()
        match = re.match(r"<\s*([^\s/>]+)", node.source_opening or "")
        node.source_tag = match.group(1) if match else node.tag
        node.source_attrs = tuple(node.attrs)
        node.foreign_content = node.tag in {"svg", "math"} or any(
            parent.tag in {"svg", "math"} for parent in self.stack
        )

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        node = element(tag, self.attributes(attrs))
        self.remember_opening(node)
        self.add(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        node = element(tag, self.attributes(attrs))
        self.remember_opening(node)
        node.self_closing = tag not in VOID
        self.add(node)

    def handle_endtag(self, tag: str) -> None:
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                return
        raise ValueError(f"Unmatched closing tag </{tag}>; refusing a lossy transform")

    def handle_data(self, data: str) -> None:
        self.add(text_node(data))

    def handle_entityref(self, name: str) -> None:
        self.add(text_node(f"&{name};"))

    def handle_charref(self, name: str) -> None:
        self.add(text_node(f"&#{name};"))

    def handle_comment(self, data: str) -> None:
        self.add(Node(raw=f"<!--{data}-->", kind="comment"))

    def handle_decl(self, decl: str) -> None:
        self.add(Node(raw=f"<!{decl}>", kind="declaration"))

    def handle_pi(self, data: str) -> None:
        self.add(Node(raw=f"<?{data}>", kind="declaration"))


def parse(source: str) -> Node:
    parser = DocumentParser()
    parser.feed(source)
    parser.close()
    if len(parser.stack) != 1:
        raise ValueError(f"Unclosed <{parser.stack[-1].tag}>; refusing a lossy transform")
    return parser.document


def walk(node: Node) -> Iterator[Node]:
    yield node
    for child in node.children:
        yield from walk(child)


def find(node: Node, predicate: Callable[[Node], bool]) -> Node | None:
    return next((item for item in walk(node) if predicate(item)), None)


def text_content(node: Node) -> str:
    if node.kind == "text":
        return html.unescape(node.raw)
    return "".join(text_content(child) for child in node.children if child.kind != "comment")


def source_content(node: Node) -> str:
    return "".join(child.raw for child in node.children)


def render(node: Node) -> str:
    if node.kind not in {"document", "element"}:
        return node.raw
    if node.kind == "document":
        return "\n".join(render(child) for child in node.children
                         if not (child.kind == "text" and not child.raw.strip())) + "\n"
    attrs = "".join(" " + key if value is None else f' {key}="{html.escape(value, quote=True)}"'
                    for key, value in node.attrs)
    # Preserve unchanged foreign-content tags exactly, including SVG element
    # casing and self-closing whitespace.  Ordinary HTML retains canonical
    # attribute escaping so generator output remains reproducible.
    tag = node.source_tag if node.foreign_content and node.source_tag and node.source_tag.lower() == node.tag else node.tag
    unchanged_opening = (node.foreign_content and node.source_opening is not None and
                         tuple(node.attrs) == node.source_attrs and
                         node.source_tag is not None and node.source_tag.lower() == node.tag)
    opening = node.source_opening if unchanged_opening else f"<{tag}{attrs}>"
    if node.tag in VOID:
        return opening
    if node.self_closing:
        return node.source_opening if unchanged_opening else f"<{tag}{attrs} />"
    if node.tag in {"html", "head", "body"}:
        children = "\n".join(render(child) for child in node.children
                             if not (child.kind == "text" and not child.raw.strip()))
        return f"{opening}\n{children}\n</{tag}>"
    return opening + "".join(render(child) for child in node.children) + f"</{tag}>"


def is_google_font_link(node: Node) -> bool:
    return node.tag == "link" and urlsplit(node.get("href")).hostname in GOOGLE_FONT_HOSTS


def css_rebase(css: str) -> str:
    """Keep root-page relative asset URLs valid after moving CSS under assets/."""
    def replace(match: re.Match[str]) -> str:
        quote, value = match.group(1), match.group(2).strip()
        if not value or value.startswith(("/", "#")) or urlsplit(value).scheme:
            return match.group(0)
        return f"url({quote}/{value.removeprefix('./')}{quote})"
    return re.sub(r"url\(\s*(['\"]?)([^)'\"]+)\1\s*\)", replace, css, flags=re.I)


def combine_robots(values: list[str]) -> str:
    directives: list[str] = []
    for value in values:
        for part in value.split(","):
            directive = part.strip().lower()
            if directive and directive not in directives:
                directives.append(directive)
    if "none" in directives:
        directives = [part for part in directives if part not in {"none", "index", "follow", "all"}]
        directives.extend(part for part in ("noindex", "nofollow") if part not in directives)
    if "noindex" in directives:
        directives = [part for part in directives if part not in {"index", "all"}]
    if "nofollow" in directives:
        directives = [part for part in directives if part not in {"follow", "all"}]
    return ", ".join(directives) or "index, follow"


def metadata(head: Node, name: str) -> str:
    node = find(head, lambda item: item.tag == "meta" and item.get("name").lower() == name)
    return node.get("content") if node else ""


def structured_data(document: Node, head: Node, filename: str, canonical: str) -> dict:
    title = find(head, lambda item: item.tag == "title")
    title_text = " ".join(text_content(title).split()) if title else "Vektorium"
    heading = find(document, lambda item: item.tag == "h1")
    heading_text = " ".join(text_content(heading).split()) if heading else title_text
    html_node = find(document, lambda item: item.tag == "html")
    language = html_node.get("lang", "en") if html_node else "en"
    organization_id = ORIGIN + "/#organization"
    website_id = ORIGIN + "/#website"
    organization = {
        "@type": "Organization", "@id": organization_id,
        "name": "Vektorium", "legalName": "Vektorium Inc.",
        "url": ORIGIN + "/", "logo": ORIGIN + LOGO,
        "contactPoint": {"@type": "ContactPoint", "email": EMAIL,
                         "contactType": "business inquiries"},
    }
    website = {
        "@type": "WebSite", "@id": website_id, "name": "Vektorium",
        "url": ORIGIN + "/", "publisher": {"@id": organization_id},
        "inLanguage": language,
    }
    webpage = {
        "@type": "WebPage", "@id": canonical + "#webpage", "url": canonical,
        "name": title_text, "isPartOf": {"@id": website_id},
        "publisher": {"@id": organization_id}, "inLanguage": language,
    }
    description = metadata(head, "description").strip()
    if description:
        webpage["description"] = description
    graph: list[dict] = [organization, website, webpage]
    if filename != "index.html":
        breadcrumb_id = canonical + "#breadcrumb"
        webpage["breadcrumb"] = {"@id": breadcrumb_id}
        graph.append({
            "@type": "BreadcrumbList", "@id": breadcrumb_id,
            "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "Home", "item": ORIGIN + "/"},
                {"@type": "ListItem", "position": 2, "name": heading_text, "item": canonical},
            ],
        })
    if filename == "cypher-sentinel.html":
        software_id = ORIGIN + "/cypher-sentinel#software"
        webpage["mainEntity"] = {"@id": software_id}
        graph.append({
            "@type": "SoftwareApplication", "@id": software_id,
            "name": "Cypher Sentinel", "url": canonical,
            "applicationCategory": "SecurityApplication",
            "publisher": {"@id": organization_id},
        })
    return {"@context": "https://schema.org", "@graph": graph}


def mobile_navigation(route: str) -> Node:
    links = []
    for href, label in NAV_LINKS:
        attrs: list[tuple[str, str | None]] = [("href", href)]
        if href == route:
            attrs.append(("aria-current", "page"))
        links.append(element("a", attrs, [text_node(html.escape(label))]))
    brand = element("a", [("class", "vx-mobile-brand"), ("href", "/"),
                          ("aria-label", "Vektorium home")], [
        element("img", [("src", LOGO), ("width", "32"), ("height", "32"),
                        ("alt", ""), ("decoding", "async")]),
        text_node("Vektorium"),
    ])
    menu = element("details", [("class", "vx-mobile-menu")], [
        element("summary", children=[text_node("Menu")]),
        element("nav", [("aria-label", "Mobile navigation")], links),
    ])
    return element("div", [("class", "vx-mobile-header")], [brand, menu])


@dataclass
class TransformResult:
    html: str
    css: str
    report: dict


def transform_page(source: str, filename: str, existing_css: str | None = None,
                   *, normalize_schema: bool = False) -> TransformResult:
    """Pure transformation; source, CSS, and report are returned, never written."""
    if filename in EXCLUDED or Path(filename).name != filename or not filename.endswith(".html"):
        raise ValueError(f"Out-of-scope page: {filename}")
    document = parse(source)
    head = find(document, lambda item: item.tag == "head")
    body = find(document, lambda item: item.tag == "body")
    if head is None or body is None:
        raise ValueError(f"{filename}: a complete head and body are required")
    stem = Path(filename).stem
    route = "/" if filename == "index.html" else "/" + stem
    canonical = ORIGIN + route
    css_url = f"/assets/styles/{stem}.css"
    already_linked = any(item.tag == "link" and item.get("href") == css_url for item in walk(head))
    capability_visuals = any(item.tag == "link" and item.get("href") == "/assets/capability-visuals.css"
                             for item in walk(head))
    if already_linked and (existing_css is None or not existing_css.startswith(CSS_HEADER)):
        raise ValueError(f"{filename}: generated CSS is missing or has an unrecognized header")
    stats = {"styles_extracted": 0, "inline_styles_converted": 0,
             "scripts_removed": 0, "event_handlers_removed": 0,
             "font_links_removed": 0, "cursor_nodes_removed": 0,
             "canvases_removed": 0, "counters_made_static": 0,
             "structured_data_preserved": 0, "decorative_nodes_preserved": 0}
    styles: list[str] = []
    inline_styles: dict[str, str] = {}

    def clean(parent: Node) -> None:
        keep: list[Node] = []
        for node in parent.children:
            if node.tag == "script":
                if node.get("type").strip().lower() == "application/ld+json" and not normalize_schema:
                    # Keep script contents verbatim, including every application
                    # claim, number, and string.  JSON is data, not executable JS.
                    stats["structured_data_preserved"] += 1
                else:
                    stats["scripts_removed"] += 1
                    continue
            if node.tag == "style":
                css = source_content(node).strip()
                media = node.get("media").strip()
                if media:
                    css = f"@media {media} {{\n{css}\n}}"
                if css:
                    styles.append(css_rebase(css))
                stats["styles_extracted"] += 1
                continue
            if is_google_font_link(node):
                stats["font_links_removed"] += 1
                continue
            if node.get("id") in {"cursorDot", "cursorRing", "fluidCanvas", "scrollIndicator"} or set(node.classes()) & {"cursor-dot", "cursor-ring", "canvas-wrapper"}:
                # Keep the original effects hooks.  Desktop effects are enabled
                # only by the approved external runtime; the shared stylesheet
                # supplies static, native-cursor mobile/no-JS fallbacks.
                node.set("aria-hidden", "true")
                stats["decorative_nodes_preserved"] += 1
            if set(node.classes()) & {"vx-skip-link", "vx-mobile-header"}:
                continue
            if node.tag == "link" and node.get("href") in SHARED_STYLES | {css_url}:
                continue
            for attr, _ in node.attrs[:]:
                if attr.casefold().startswith("on"):
                    node.drop(attr)
                    stats["event_handlers_removed"] += 1
            if node.has("style"):
                style = node.get("style").strip()
                node.drop("style")
                if style:
                    classname = "vx-style-" + hashlib.sha256(style.encode("utf-8")).hexdigest()[:16]
                    node.add_class(classname)
                    inline_styles.setdefault(classname, css_rebase(style))
                stats["inline_styles_converted"] += 1
            target = node.get("data-target") or node.get("data-count")
            if target and re.fullmatch(r"\d+(?:\.\d+)?", target) and re.fullmatch(r"0(?:\.0+)?", text_content(node).strip()):
                if all(child.kind == "text" for child in node.children):
                    value = f"{int(target):,}" if target.isdigit() else target
                    node.children = [text_node(value)]
                    stats["counters_made_static"] += 1
            if node.tag == "img":
                image_path = urlsplit(node.get("src")).path.lstrip("/")
                if image_path in {"vektorium-logo.png", "vektorium-logo.webp",
                                  "vektorium-logo-1x.webp", "vektorium-logo-2x.webp"}:
                    # All current logo variants are square except the legacy PNG.
                    # Use the square WebP, retaining template CSS's display sizes.
                    node.set("src", LOGO)
                    node.set("width", "240")
                    node.set("height", "240")
                    node.set("decoding", "async")
            if node.tag == "a" and node.get("target").lower() == "_blank":
                rel = node.get("rel").split()
                if "noopener" not in rel:
                    rel.append("noopener")
                node.set("rel", " ".join(rel))
            if node.tag == "button" and node.get("id") == "copyBtn":
                node.set("type", "button")
                node.set("aria-label", "Copy email to clipboard")
            clean(node)
            if node.tag == "noscript" and not any(child.tag or (child.kind == "text" and child.raw.strip()) for child in node.children):
                continue
            keep.append(node)
        parent.children = keep

    clean(document)
    main_nodes = [item for item in walk(body) if item.tag == "main"]
    if len(main_nodes) > 1:
        raise ValueError(f"{filename}: more than one main landmark")
    main = main_nodes[0] if main_nodes else find(body, lambda item: "content-wrapper" in item.classes())
    if main is None:
        raise ValueError(f"{filename}: no main or content-wrapper; manual landmark choice required")
    main.tag = "main"
    old_main_id = main.get("id")
    if old_main_id and old_main_id != "main-content":
        # Preserve any old fragment target used by external or internal links.
        main.children.insert(0, element("span", [("id", old_main_id), ("aria-hidden", "true")]))
    for item in walk(body):
        if item is not main and item.get("id") == "main-content":
            raise ValueError(f"{filename}: #main-content already belongs to a different element")
    main.set("id", "main-content")
    main.set("tabindex", "-1")
    body.children[:0] = [
        element("a", [("class", "vx-skip-link"), ("href", "#main-content")], [text_node("Skip to content")]),
        mobile_navigation(route),
    ]

    # Put disclosure alongside the existing footer resources without replacing
    # desktop navigation or the page's existing information architecture.
    for footer in (item for item in walk(body) if item.tag == "footer"):
        if not any(item.tag == "a" and item.get("href") == "/security" for item in walk(footer)):
            resource_column = find(footer, lambda item: "footer-col" in item.classes() and
                                   any(child.tag in {"h2", "h3", "h4"} and
                                       "resources" in text_content(child).lower() for child in item.children))
            if resource_column:
                resource_column.children.append(element("a", [("href", "/security")], [text_node("Security &amp; disclosure")]))

    robots = [item for item in walk(head) if item.tag == "meta" and item.get("name").lower() == "robots"]
    robot_value = combine_robots([item.get("content") for item in robots])
    authors = [item.get("content").strip() for item in walk(head)
               if item.tag == "meta" and item.get("name").lower() == "author" and item.get("content").strip()]
    author = authors[0] if authors else "Vektorium Inc."
    seen_meta: set[tuple[str, str]] = set()
    retained: list[Node] = []
    for item in head.children:
        if item.tag == "meta":
            name = item.get("name").lower()
            prop = item.get("property").lower()
            if name in {"keywords", "robots", "author"}:
                continue
            if name in {"google-site-verification", "msvalidate.01"} and not item.get("content").strip():
                continue
            if filename == "contact.html" and (prop == "og:image" or name == "twitter:image") and urlsplit(item.get("content")).path == "/og-image.webp":
                item.set("content", ORIGIN + LOGO)
            if prop == "og:url":
                item.set("content", canonical)
            # Dedupe exact copies only; do not silently discard conflicting copy.
            key = ("name:" + name if name else "property:" + prop, item.get("content"))
            if (name or prop) and key in seen_meta:
                continue
            seen_meta.add(key)
        if item.tag == "link" and "canonical" in item.get("rel").lower().split():
            continue
        retained.append(item)
    head.children = retained
    head.children.extend([
        element("meta", [("name", "robots"), ("content", robot_value)]),
        element("meta", [("name", "author"), ("content", author)]),
        element("link", [("rel", "canonical"), ("href", canonical)]),
    ])

    schema_types: list[str] = []
    if normalize_schema:
        graph = structured_data(document, head, filename, canonical)
        json_text = json.dumps(graph, ensure_ascii=False, indent=2).replace("<", "\\u003c")
        head.children.append(element("script", [("type", "application/ld+json"), ("id", "vx-structured-data")],
                                     [text_node("\n" + json_text + "\n")]))
        schema_types = [item["@type"] for item in graph["@graph"]]
    # Self-hosted font declarations precede the original page stylesheet.  The
    # shared accessible defaults precede desktop-only progressive enhancement.
    head.children.extend([
        element("link", [("rel", "stylesheet"), ("href", "/assets/fonts.css")]),
        element("link", [("rel", "stylesheet"), ("href", css_url)]),
    ])
    if capability_visuals:
        head.children.append(element("link", [("rel", "stylesheet"), ("href", "/assets/capability-visuals.css")]))
    head.children.extend([
        element("link", [("rel", "stylesheet"), ("href", "/assets/site.css")]),
    ])
    desktop_effects = any(item.get("id") in {"cursorDot", "cursorRing", "fluidCanvas"} for item in walk(body))
    if desktop_effects:
        head.children.append(element("link", [("rel", "stylesheet"), ("href", "/assets/desktop-effects.css")]))
    head.children.append(element("script", [("src", "/assets/site.js"), ("defer", None)]))
    if desktop_effects:
        head.children.append(element("script", [("src", "/assets/desktop-effects.js"), ("defer", None)]))

    if already_linked:
        css = existing_css.rstrip() + "\n"  # type: ignore[union-attr]
        if styles:
            css += "\n" + "\n\n".join(styles) + "\n"
    else:
        css = CSS_HEADER + "\n\n" + "\n\n".join(styles).rstrip() + "\n"
    for classname, declaration in inline_styles.items():
        selector = f":is(#vx-inline-style-priority, .{classname})"
        if selector + " {" not in css:
            # ID specificity approximates the old inline-style precedence while
            # leaving existing !important declarations and shared overrides intact.
            css += f"\n{selector} {{ {declaration} }}\n"
    css = css.rstrip() + "\n"
    output = render(document)
    verify(document, filename)
    return TransformResult(output, css, {
        "page": filename, "canonical": canonical, "stylesheet": css_url,
        "changed_html": output != source, "changed_css": css != existing_css,
        "schema_mode": "normalized" if normalize_schema else "preserved",
        "desktop_effects": desktop_effects,
        "normalized_schema_types": schema_types, **stats,
    })


def verify(document: Node, filename: str) -> None:
    for item in walk(document):
        if item.tag == "style":
            raise ValueError(f"{filename}: remaining <{item.tag}>")
        if any(name.casefold() == "style" or name.casefold().startswith("on") for name, _ in item.attrs):
            raise ValueError(f"{filename}: inline style/event handler survived")
        if item.tag == "script" and not (item.get("type").strip().lower() == "application/ld+json" or item.get("src") in APPROVED_SCRIPTS):
            raise ValueError(f"{filename}: unexpected script survived")
        if is_google_font_link(item):
            raise ValueError(f"{filename}: Google Font link survived")
    if len([item for item in walk(document) if item.tag == "main" and item.get("id") == "main-content"]) != 1:
        raise ValueError(f"{filename}: exactly one main landmark required")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1],
                        help="Website repository (defaults to this script's parent repository)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="Write the proposed changes locally (never deploy)")
    mode.add_argument("--check", action="store_true", help="Read-only check; exit 1 if a transformation is needed")
    parser.add_argument("--normalize-schema", action="store_true",
                        help="Explicitly replace existing JSON-LD claims with the minimal graph; off by default")
    args = parser.parse_args(argv)
    repo = args.repo.resolve(strict=True)
    pages = sorted(path for path in repo.glob("*.html") if path.name not in EXCLUDED)
    if not pages:
        parser.error("No ordinary HTML pages found")
    planned: list[tuple[Path, Path, TransformResult]] = []
    for path in pages:
        if path.is_symlink():
            parser.error(f"Refusing symlinked input: {path.name}")
        css_path = repo / "assets" / "styles" / (path.stem + ".css")
        if not css_path.resolve().is_relative_to(repo) or css_path.is_symlink():
            parser.error(f"Refusing stylesheet path outside the repository: {css_path}")
        source = path.read_text(encoding="utf-8")
        existing_css = css_path.read_text(encoding="utf-8") if css_path.exists() else None
        result = transform_page(source, path.name, existing_css, normalize_schema=args.normalize_schema)
        # Verify exact idempotence in memory before any file is written.
        second = transform_page(result.html, path.name, result.css, normalize_schema=args.normalize_schema)
        if second.html != result.html or second.css != result.css:
            raise ValueError(f"{path.name}: transform is not idempotent; no files written")
        planned.append((path, css_path, result))
    if args.apply:
        for path, css_path, result in planned:
            css_path.parent.mkdir(parents=True, exist_ok=True)
            if result.report["changed_css"]:
                css_path.write_text(result.css, encoding="utf-8")
            if result.report["changed_html"]:
                path.write_text(result.html, encoding="utf-8")
    report = {"mode": "apply" if args.apply else "check" if args.check else "dry-run",
              "schema_mode": "normalized" if args.normalize_schema else "preserved",
              "page_count": len(planned), "excluded": sorted(EXCLUDED),
              "pages": [result.report for _, _, result in planned]}
    print(json.dumps(report, indent=2, ensure_ascii=False))
    changed = any(result.report["changed_html"] or result.report["changed_css"] for _, _, result in planned)
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        print(f"harden_site: {error}", file=sys.stderr)
        raise SystemExit(2)
